-- 1. Criar uma Sequence com CACHE e controle de limites

CREATE SEQUENCE seq_clientes_id
    START WITH 1000
    INCREMENT BY 1
    MINVALUE 1000
    MAXVALUE 999999
    CACHE 20
    NOCYCLE;


-- 2. Consumir e avançar valores com NEXTVAL

SELECT seq_clientes_id.NEXTVAL AS proximo_id
FROM DUAL;


-- 3. Consultar o valor corrente com CURRVAL

SELECT seq_clientes_id.CURRVAL AS id_atual
FROM DUAL;


-- 4. Avançar novamente a Sequence

SELECT seq_clientes_id.NEXTVAL AS novo_id
FROM DUAL;


