/* ============================================================
   EXERCÍCIO 2 - TRIGGER VS DEFAULT
   ============================================================ */

-- Criar Sequence para demonstração com Trigger

CREATE SEQUENCE seq_funcionarios_id
    START WITH 1
    INCREMENT BY 1
    CACHE 20
    NOCYCLE;


-- Criar tabela de funcionários para o exemplo

CREATE TABLE tb_funcionarios_trigger (
    id_funcionario NUMBER PRIMARY KEY,
    nome           VARCHAR2(100) NOT NULL
);


-- Criar Trigger BEFORE INSERT

CREATE OR REPLACE TRIGGER trg_funcionarios_id
BEFORE INSERT ON tb_funcionarios_trigger
FOR EACH ROW
WHEN (NEW.id_funcionario IS NULL)
BEGIN
    :NEW.id_funcionario := seq_funcionarios_id.NEXTVAL;
END;
/


